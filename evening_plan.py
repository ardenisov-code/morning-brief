# ── Rotation logic ─────────────────────────────────────────────────────────────
def get_evening_sessions(dates: list) -> list:
    """
    Given a list of date objects, return list of (label, session) tuples.
    Within each weekday slot, sessions rotate week by week.
    """
    day_ru = {
        "Monday": "Пн", "Tuesday": "Вт", "Wednesday": "Ср",
        "Thursday": "Чт", "Friday": "Пт", "Saturday": "Сб", "Sunday": "Вс",
    }
    result = []
    for i, d in enumerate(dates):
        weekday = d.weekday()  # 0=Mon … 6=Sun
        pool = SESSIONS_BY_WEEKDAY[weekday]
        week_num = d.timetuple().tm_yday  # day-of-year: каждый день — разная тема
        session = pool[week_num % len(pool)]
        if i == 0:
            label = "Сегодня"
        elif i == 1:
            label = "Завтра"
        else:
            label = day_ru.get(d.strftime("%A"), d.strftime("%a"))
        result.append((label, d, session))
    return result


def format_evening_block(num_days: int = 3) -> str:
    """Return formatted Telegram markdown block for evening sessions."""
    from datetime import timedelta
    today = date.today()
    dates = [today + timedelta(days=i) for i in range(num_days)]
    sessions = get_evening_sessions(dates)

    lines = ["🌙 *Вечерний час (20:00)*"]
    for label, d, s in sessions:
        date_str = d.strftime("%-d %b")
        lines.append(f"\n*{label} ({date_str}) — {s['topic']}*")
        lines.append(f"_{s['title']}_")
        lines.append(s["task"])
        lines.append(s["material"])

    return "\n".join(lines)
